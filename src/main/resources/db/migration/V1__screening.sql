-- The screening snapshot (roadmap Step 3) and saved screens (Step 8). Each run keeps its own rows, so earlier
-- snapshots stay available for history and watchlist diffs. Migrations are never edited once released: a change
-- is a new V<n>__*.sql.

CREATE TABLE snapshot_run (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    universe          VARCHAR(40)              NOT NULL,
    snapshot_date     DATE                     NOT NULL,
    started_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at       TIMESTAMP WITH TIME ZONE,
    status            VARCHAR(20)              NOT NULL,
    symbols_requested INT                      NOT NULL,
    symbols_stored    INT                      NOT NULL DEFAULT 0,
    symbols_failed    INT                      NOT NULL DEFAULT 0
);
CREATE INDEX snapshot_run_latest_idx ON snapshot_run (universe, status, finished_at DESC);

CREATE TABLE fundamentals_snapshot (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               BIGINT                   NOT NULL REFERENCES snapshot_run (id),
    symbol               VARCHAR(40)              NOT NULL,
    company_name         VARCHAR(300),
    industry_group       VARCHAR(40)              NOT NULL,
    classification_basis TEXT,
    snapshot_date        DATE                     NOT NULL,
    captured_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    -- how many fiscal years were read from the NSE filings; null in runs made before it was recorded
    filed_fiscal_years   INT,
    UNIQUE (run_id, symbol)
);

-- One row per metric, with its DataStatus as the research layer produced it.
CREATE TABLE snapshot_metric (
    snapshot_id      BIGINT         NOT NULL REFERENCES fundamentals_snapshot (id),
    metric           VARCHAR(60)    NOT NULL,
    metric_value     DECIMAL(30, 8),
    metric_unit      VARCHAR(20),
    display          VARCHAR(200)   NOT NULL,
    data_status      VARCHAR(20)    NOT NULL,
    status_reason    TEXT,
    period_label     VARCHAR(200),
    source           TEXT,
    calculation      TEXT,
    unchecked_reason TEXT,
    PRIMARY KEY (snapshot_id, metric)
);

CREATE TABLE snapshot_failure (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT      NOT NULL REFERENCES snapshot_run (id),
    symbol VARCHAR(40) NOT NULL,
    reason TEXT        NOT NULL
);
CREATE INDEX snapshot_failure_run_idx ON snapshot_failure (run_id);

-- A screen saved for watchlist monitoring (roadmap Step 8, S8-6): re-run deterministically, by preset and
-- universe, against the two newest completed snapshots, never by the model.
CREATE TABLE saved_screen (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(200)             NOT NULL UNIQUE,
    universe       VARCHAR(40)              NOT NULL,
    preset         VARCHAR(100)             NOT NULL,
    industry_group VARCHAR(40),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
